// Runs the main flow in WebKit with the iPhone 13 profile (touch, 3x DPR) against the dev server
// on port 5174 and reports console errors, WebGL support, horizontal overflow and frame rate.
// Usage: npm run e2e:mobile (dev server on port 5174; WebKit from `npx playwright install webkit`)
import { createRequire } from 'node:module'
import { mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
const require = createRequire(resolve(process.argv[2]) + '/')
const { webkit, devices } = require('playwright')
const out = resolve(process.argv[3])
mkdirSync(out, { recursive: true })
const browser = await webkit.launch()
const context = await browser.newContext({ ...devices['iPhone 13'] })
const page = await context.newPage()
const errors = []
page.on('console', (m) => m.type() === 'error' && errors.push(m.text().slice(0, 160)))
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
await page.goto('http://localhost:5174', { waitUntil: 'networkidle' })
await page.evaluate(() => localStorage.clear())
await page.reload({ waitUntil: 'networkidle' })
const overflow = () => page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth)
const report = { device: 'iPhone 13 (WebKit)', viewport: page.viewportSize() }
report.welcomeOverflowPx = await overflow()
await page.screenshot({ path: `${out}/m1-welcome.png` })
await page.getByText('Ride hailing (Uber)').tap()
await page.waitForTimeout(1500)
await page.getByRole('button', { name: /Not sure/ }).tap()
await page.waitForTimeout(500)
await page.getByText('Auto-design the rest with recommendations').tap()
await page.waitForTimeout(3000)
report.webgl = await page.evaluate(() => { const c = document.querySelector('canvas'); return !!(c && (c.getContext('webgl2') || c.getContext('webgl'))) })
report.components = await page.locator('.hud-value').nth(4).textContent()
report.labels = await page.locator('.label-layer .label').count()
report.visibleLabels = await page.evaluate(() => [...document.querySelectorAll('.label-layer .label')].filter((l) => l.style.display !== 'none' && l.style.transform).length)
report.workspaceOverflowPx = await overflow()
report.fps = await page.evaluate(() => new Promise((r) => { let n = 0; const t0 = performance.now(); const f = () => { n++; performance.now() - t0 < 2000 ? requestAnimationFrame(f) : r(n / 2) }; requestAnimationFrame(f) }))
await page.screenshot({ path: `${out}/m2-workspace.png` })
await page.getByRole('button', { name: 'Documentation', exact: true }).tap()
await page.waitForTimeout(800)
report.docsAdrCount = await page.locator('.markdown h3').count()
report.docsOverflowPx = await overflow()
await page.screenshot({ path: `${out}/m3-docs.png` })
await page.getByRole('button', { name: 'Close', exact: true }).tap()
await page.getByRole('button', { name: 'Explore and versions', exact: true }).tap()
await page.waitForTimeout(1200)
await page.screenshot({ path: `${out}/m4-explore.png` })
report.exploreOverflowPx = await overflow()
report.errors = errors
console.log(JSON.stringify(report, null, 1))
await browser.close()
