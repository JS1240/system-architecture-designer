/** One line naming a source: a repository file with its lines, or general practice for a 'general' source. */
export const cite = (s: SourceRef) => (s.repo === 'general' ? `General practice: ${s.title}` : `${s.repo}/${s.path}${s.lines ? `:${s.lines}` : ''} (${s.title})`)
/** The web page a 'general' source points to, when its path is a URL. */
export const sourceUrl = (s: SourceRef) => (s.repo === 'general' && /^https?:\/\//.test(s.path) ? s.path : undefined)

